import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root=new URL('../',import.meta.url);
const destination=new URL('src/features/characters/rules/races.mjs',root);
const movementDestination=new URL('src/features/sheet/racial-land-speeds.mjs',root);
const omitted=new Set(['sourceRefs','contentSha256','dependencies','review','excludedSections','extractionAudit','automationContract','contractRevision','sheetMapping']);
function lean(value){
 if(Array.isArray(value))return value.map(lean);
 if(value&&typeof value==='object')return Object.fromEntries(Object.entries(value).filter(([key])=>!omitted.has(key)).map(([key,value])=>[key,lean(value)]));
 return value;
}

// This is an explicit adapter capability list. A staged effect outside these
// paths remains manual; its presence in JSON cannot turn it into a global buff.
const supported=target=>target.startsWith('ability_scores.')||target.startsWith('skills.')||target.startsWith('proficiencies.weapon.')||target.startsWith('identity.');
export function projectRaceDefinition(definition,enabledClassIds,{testing=false}={}){
 if(definition.kind!=='race'||definition.schemaVersion!=='comos.rules.v1')throw Error('Expected a comos.rules.v1 race.');
 const race=lean(definition),ids=new Set(race.features.map(f=>f.id));
 if(ids.size!==race.features.length)throw Error('Duplicate racial feature ID.');
 for(const id of [...race.data.standardTraitIds,...race.data.alternateTraitIds])if(!ids.has(id))throw Error('Missing racial trait '+id);
 for(const f of race.features)for(const effect of f.effects){
  if(effect.automation==='automatic'&&(effect.condition||!supported(effect.target)))effect.automation=effect.condition?'conditional':'manual';
 }
 race.data.favoredRewards=race.data.favoredRewards.filter(reward=>enabledClassIds.includes(reward.classId));
 if(testing){race.testing=true;race.reviewStatus='needs_review';}
 return race;
}
export async function generateRaceCatalog({check=false}={}){
 const manifest=JSON.parse(await readFile(new URL('rules/manifest.json',root),'utf8'));
 const races=[];
 for(const file of manifest.races){
  if(!/^(?:races|staging\/races)\/[a-z0-9-]+\.race\.json$/.test(file))throw Error('Invalid race definition path.');
  races.push(projectRaceDefinition(JSON.parse(await readFile(new URL('rules/'+file,root),'utf8')),manifest.enabledClassIds,{testing:file.startsWith('staging/races/')}));
 }
 if(new Set(races.map(r=>r.id)).size!==races.length)throw Error('Duplicate race ID.');
 const output='// Generated by scripts/generate-races.mjs from rules/manifest.json. Do not edit.\nexport const races='+JSON.stringify(races)+';\n';
 const movement={};
 for(const race of races){
  for(const trait of race.features){
   if(!race.data.standardTraitIds.includes(trait.id))continue;
   const effect=trait.effects.find(effect=>['identity.speed.land','speed.land'].includes(effect.target)&&
     effect.operation==='set'&&!effect.condition);
   if(!effect)continue;
   const feet=effect.value?.kind==='constant'?effect.value.value:Number(/^\d+/.exec(effect.textValue||'')?.[0]);
   if(!Number.isFinite(feet))continue;
   const ignoresSlowdown=trait.effects.some(effect=>!effect.condition&&
     ['identity.speed.armor_encumbrance_exemption','movement.armor_encumbrance'].includes(effect.target));
   movement[race.name.toLowerCase()]={feet,trait:trait.name,...(ignoresSlowdown?{ignoresSlowdown:true}:{})};
  }
 }
 const movementOutput='// Generated by scripts/generate-races.mjs. Do not edit.\nexport const racialLandSpeeds='+JSON.stringify(movement,null,2)+';\n';
 for(const [file,contents] of [[destination,output],[movementDestination,movementOutput]]){
  if(check){if(await readFile(file,'utf8')!==contents)throw Error('Race projection is stale. Run npm run rules:generate.');}
  else await writeFile(file,contents);
 }
 return races;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const races=await generateRaceCatalog({check:process.argv.includes('--check')});
 console.log((process.argv.includes('--check')?'Checked':'Generated')+' '+races.length+' individual race definitions.');
}
